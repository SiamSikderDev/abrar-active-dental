const dicts: Record<Lang, Record<DictKey, string>> = { en, bn };

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: DictKey) => string }>({
  lang: "bn",
  setLang: () => {},
  t: (k) => en[k],
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("bn");

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem("aad-lang");
      if (saved === "bn" || saved === "en") setLangState(saved);
    } catch {
      /* ignore */
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem("aad-lang", l);
    } catch {
      /* ignore */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo(
    () => ({ lang, setLang, t: (k: DictKey) => dicts[lang][k] ?? en[k] ?? k }),
    [lang, setLang]
  );
  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export function useLang() {
  return useContext(LangCtx);
}

/** Bangla digits for display when the UI language is Bangla. */
export function bnDigits(s: string | number, lang: Lang): string {
  const str = String(s);
  if (lang !== "bn") return str;
  const map: Record<string, string> = { "0": "০", "1": "১", "2": "২", "3": "৩", "4": "৪", "5": "৫", "6": "৬", "7": "৭", "8": "৮", "9": "৯" };
  return str.replace(/[0-9]/g, (d) => map[d]);
}

export function fmtMoney(n: number, lang: Lang): string {
  return `${lang === "bn" ? "৳" : "৳"}${bnDigits(n.toLocaleString("en-US"), lang)}`;
}
